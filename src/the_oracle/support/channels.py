"""Share channels for a finished bug report — links, never transport.

The support philosophy is unchanged from the crash unit: there is no upload
code. This module only composes the two deliberate acts a customer can take —
open a prefilled issue in a browser they already trust, or open their mail
client with a prefilled message. Both are plain strings; nothing here opens a
socket, and the caller decides whether to hand the string to a browser.

Length caps matter: browsers and mail clients reject very long URLs, so an
overlong report is truncated to its actionable head plus a pointer to the
attached bundle (which carries the full diagnostics).
"""

from __future__ import annotations

import platform
from urllib.parse import quote, urlencode

from the_oracle.support.report import BugReport, report_markdown

ISSUE_REPO = "kingcinder/The_Oracle_TTS"
SUPPORT_EMAIL = "codysa90@gmail.com"
MAX_ISSUE_URL_CHARS = 7500
MAX_MAILTO_URL_CHARS = 3500
MAX_MAILTO_BODY_CHARS = 1800


def issue_title(report: BugReport) -> str:
    return f"[{report.area}/{report.severity}] {report.title} — The Oracle {report.app_version}"


def issue_body(report: BugReport, *, include_diagnostics: bool = True) -> str:
    body = report_markdown(report, include_diagnostics=include_diagnostics)
    marker = "\n---\nGenerated by"
    if marker in body:
        body = body.split(marker, 1)[0].rstrip()
    return body + "\n\n_Reported from The Oracle's local bug-report flow._\n"


def _issue_link(title: str, body: str) -> str:
    query = urlencode({"title": title, "body": body, "labels": "bug"}, quote_via=quote)
    return f"https://github.com/{ISSUE_REPO}/issues/new?{query}"


def issue_url(report: BugReport) -> str:
    """A prefilled ``/issues/new`` URL. Building it never contacts GitHub.

    Browsers cap URLs, so the body degrades in a fixed order: full report,
    compact report, then a bounded head with the summary sliced ever shorter.
    Every fallback still carries the report id and the bundling instruction.
    """
    title = issue_title(report)
    for body in (
        issue_body(report),
        issue_body(report, include_diagnostics=False),
    ):
        url = _issue_link(title, body)
        if len(url) <= MAX_ISSUE_URL_CHARS:
            return url

    header = [
        f"# [The Oracle {report.app_version}] {report.title}",
        "",
        f"Report ID: {report.report_id}",
        f"Area: {report.area}   Severity: {report.severity}",
        "",
        "## Summary",
    ]
    trailer = (
        f"_Full report truncated for this link. Report ID: {report.report_id}. "
        "Attach the support bundle created by `the-oracle bug-report package`._"
    )
    for keep in (1200, 600, 200, 0):
        summary = report.summary[:keep]
        if keep and len(report.summary) > keep:
            summary += "…"
        body = "\n".join(header + [summary or "(see the attached report)", "", trailer])
        url = _issue_link(title, body)
        if len(url) <= MAX_ISSUE_URL_CHARS:
            return url
    return _issue_link(
        report.title[:80],
        f"Report ID: {report.report_id}. Full details are in the attached support bundle.",
    )


def mailto_url(report: BugReport) -> str:
    """A prefilled support email. Never sends anything by itself."""
    lines = [
        f"Report ID: {report.report_id}",
        f"The Oracle {report.app_version} on {platform.system()} {platform.release()}",
        f"Area: {report.area}   Severity: {report.severity}",
        "",
        f"Summary: {report.summary or '(see attached report)'}",
    ]
    if report.steps:
        lines.append("")
        lines.append("Steps:")
        lines.extend(f"  {index}. {step}" for index, step in enumerate(report.steps[:10], start=1))
    lines.extend(
        [
            "",
            "The support bundle and report are attached (created with "
            "`the-oracle bug-report package`).",
        ]
    )
    body = "\n".join(lines)
    if len(body) > MAX_MAILTO_BODY_CHARS:
        body = body[:MAX_MAILTO_BODY_CHARS] + "\n… (see attached report)"
    subject = issue_title(report)
    url = "mailto:" + SUPPORT_EMAIL + "?" + urlencode(
        {"subject": subject, "body": body}, quote_via=quote
    )
    if len(url) > MAX_MAILTO_URL_CHARS:
        # A pathological title is the only way to get here; trim the subject.
        subject = subject[:120]
        url = "mailto:" + SUPPORT_EMAIL + "?" + urlencode(
            {"subject": subject, "body": body[:MAX_MAILTO_BODY_CHARS // 2]}, quote_via=quote
        )
    return url


def share_note(report: BugReport) -> str:
    """The one-paragraph instruction shown after a draft is created."""
    return (
        f"Report {report.report_id} is saved on this machine. Nothing was sent.\n"
        "Next: review it (`the-oracle bug-report show "
        f"{report.report_id}`), then either package it for attachment "
        f"(`the-oracle bug-report package {report.report_id}`) or open the "
        "prefilled issue link (`the-oracle bug-report issue "
        f"{report.report_id}`)."
    )
